using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Myapp.Gate.Comments;

namespace Myapp.Gate.Code;

public sealed partial class CommentsTests
{
    private sealed record Comment(int Line, string Text);

    [GeneratedRegex(@"^/\*lang=\w+\*/$")]
    private static partial Regex LanguageMarker();

    [GeneratedRegex(@"^// </?auto-generated>$")]
    private static partial Regex GeneratedMarker();

    [Fact]
    public void No_CSharp_file_holds_a_comment_but_a_tool_marker()
    {
        var problems = SourceFile
            .All.SelectMany(file => CommentsIn(file).Where(comment => !IsAllowed(comment)).Select(comment => (file.Path, comment)))
            .Select(found => $"{found.Path}:{found.comment.Line}: {found.comment.Text.Split('\n')[0]}")
            .ToList();

        Assert.True(
            problems.Count == 0,
            $"{CommentFiles.Fix}; {problems.Count} found:{Environment.NewLine}{string.Join(Environment.NewLine, problems)}"
        );
    }

    [Theory]
    [InlineData("/*lang=json*/", true)]
    [InlineData("// <auto-generated>", true)]
    [InlineData("// </auto-generated>", true)]
    [InlineData("// Why: the pool is dropped first, grate reconnects", false)]
    [InlineData("// the clock", false)]
    [InlineData("// var x = 1;", false)]
    [InlineData("// TODO: later", false)]
    [InlineData("/* a block */", false)]
    [InlineData("/// <summary>x</summary>", false)]
    [InlineData("/** <summary>x</summary> */", false)]
    [InlineData("/*lang=json*/ // and more", false)]
    public void The_rules_judge_a_comment(string text, bool allowed)
    {
        var comments = CommentsIn(new SourceFile("Myapp.Server/X.cs", text + "\nclass X;")).ToList();

        Assert.Equal(allowed, comments.All(IsAllowed));
    }

    [Fact]
    public void Comment_signs_inside_strings_are_not_comments()
    {
        var source = "var a = \"http://x\"; var b = @\"// no\"; var c = \"\"\"\n// no\n\"\"\"; var d = '\"'; // yes";

        var comments = CommentsIn(new SourceFile("X.cs", source));

        Assert.Equal(["// yes"], comments.Select(comment => comment.Text));
    }

    private static IEnumerable<Comment> CommentsIn(SourceFile file) =>
        file
            .Root.DescendantTrivia()
            .Where(trivia =>
                trivia.Kind()
                    is SyntaxKind.SingleLineCommentTrivia
                        or SyntaxKind.MultiLineCommentTrivia
                        or SyntaxKind.SingleLineDocumentationCommentTrivia
                        or SyntaxKind.MultiLineDocumentationCommentTrivia
            )
            .Select(trivia => new Comment(trivia.GetLocation().GetLineSpan().StartLinePosition.Line + 1, trivia.ToString().Trim()));

    private static bool IsAllowed(Comment comment) => LanguageMarker().IsMatch(comment.Text) || GeneratedMarker().IsMatch(comment.Text);
}
